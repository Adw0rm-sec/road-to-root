<h3>Uploading files</h3>
<p>Head to the <a href="/upload.php">Upload</a> page, choose a file, and press
Upload. Your file is stored in the share folder and served back at a
<code>/uploads/&lt;name&gt;</code> link you can send to colleagues.</p>
<p>For images specifically, the <a href="/share.php">Share an image</a> page
posts to the shared gallery.</p>
